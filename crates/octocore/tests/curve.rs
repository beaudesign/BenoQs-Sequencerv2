// ------------------------------------------------------------------ the table's shape (CV-2 to CV-4, CV-8)

fn curve_starts(w: Warp, level: u8, n: u8) -> Vec<u32> {
    (1..=n).map(|k| roll_start_ticks(ChordStyle::Curve(w), level, k, n)).collect()
}

fn gaps(starts: &[u32]) -> Vec<i64> {
    starts.windows(2).map(|p| p[1] as i64 - p[0] as i64).collect()
}

