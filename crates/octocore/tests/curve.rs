/// Starts are whole ticks, so a gap can be a tick off what the formula says, and two gaps that the
/// formula orders can swap by one when they are nearly equal. "Never grow" therefore means: by no
/// more than one tick, and the roll as a whole does run from wide to narrow (or the reverse).
#[test]
fn cv4_the_sign_means_what_it_says() {
    for level in 1..=9u8 {
        for n in 3..=7u8 {
            let bounce = gaps(&curve_starts(Warp::Bounce, level, n));
            let accel = gaps(&curve_starts(Warp::Accel, level, n));
            let rit = gaps(&curve_starts(Warp::Rit, level, n));
            let drag = gaps(&curve_starts(Warp::Drag, level, n));
            for (name, g) in [("Bounce", &bounce), ("Accel", &accel)] {
                assert!(g.windows(2).all(|p| p[1] <= p[0] + 1), "{name} level {level} n {n}: a gap grew by more than a tick: {g:?}");
                assert!(g[0] >= *g.last().unwrap(), "{name} level {level} n {n}: it does not accelerate: {g:?}");
            }
            for (name, g) in [("Rit", &rit), ("Drag", &drag)] {
                assert!(g.windows(2).all(|p| p[1] + 1 >= p[0]), "{name} level {level} n {n}: a gap shrank by more than a tick: {g:?}");
                assert!(g[0] <= *g.last().unwrap(), "{name} level {level} n {n}: it does not drag: {g:?}");
            }
        }
    }
}

#[test]
