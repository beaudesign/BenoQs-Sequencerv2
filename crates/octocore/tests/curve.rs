// ------------------------------------------------------------------ the engine, played

struct Played {
    /// NoteOns as (tick after the first, note, velocity, channel, port).
    ons: Vec<(u64, u8, u8, u8, u8)>,
    /// For each NoteOn in order of sample, the length in samples to its NoteOff of the same key (the first off after it, in order).
    lengths: Vec<u64>,
}

/// One strummed step on track 0: a chord of `size` notes (1 is a single note), every one of them
/// played (polyphony equals the chord size), in the style given, at 120 BPM.
fn play(style: ChordStyle, level: i8, size: usize) -> Played {
    let mut engine = Engine::new(0);
    set_chord(&mut engine, 0, size, size as u8, level);
    assert!(engine.set_chord_style(0, style));
    let mut events: Vec<(u64, Event)> = Vec::new();
    let mut clock = 0u64;
    for _ in 0..16 {
        let mut buf = EventBuffer::new();
        engine.render(&RenderContext { sample_rate: SAMPLE_RATE, buffer_len: BUFFER, bpm: 120.0, playing: true }, &mut buf);
        for e in buf.as_slice() {
            let at = match *e {
                Event::NoteOn { at_sample, .. } | Event::NoteOff { at_sample, .. } | Event::Cc { at_sample, .. } | Event::PitchBend { at_sample, .. } | Event::ChannelPressure { at_sample, .. } => at_sample,
            };
            events.push((clock + at as u64, *e));
        }
        clock += BUFFER as u64;
    }
    let first = events.iter().find_map(|(at, e)| matches!(e, Event::NoteOn { .. }).then_some(*at)).expect("a note sounded");
    let mut open: BTreeMap<(u8, u8, u8), Vec<u64>> = BTreeMap::new();
    let mut ons = Vec::new();
    let mut ons_at = Vec::new();
    let mut length_of: BTreeMap<u64, u64> = BTreeMap::new();
    for (at, e) in &events {
        match *e {
            Event::NoteOn { port, ch, note, vel, .. } => {
                assert_eq!((at - first) % TICK, 0, "a note starts on a whole tick");
                ons.push(((at - first) / TICK, note, vel, ch, port));
                ons_at.push(*at);
                open.entry((port, ch, note)).or_default().push(*at);
            }
            Event::NoteOff { port, ch, note, .. } => {
                if let Some(q) = open.get_mut(&(port, ch, note)) {
                    if !q.is_empty() {
                        let on = q.remove(0);
                        length_of.entry(on).or_insert(at - on);
                    }
                }
            }
            _ => {}
        }
    }
    let lengths = ons_at.iter().map(|a| *length_of.get(a).unwrap_or(&0)).collect();
    Played { ons, lengths }
}

fn ticks(p: &Played) -> Vec<u64> {
    p.ons.iter().map(|o| o.0).collect()
}

