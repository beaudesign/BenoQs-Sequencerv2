// ------------------------------------------------------------------ the formula, and the table (CV-9)

/// Half up: 2.5 is 3, 2.4999 is 2.
fn half_up(x: f64) -> i64 {
    (x + 0.5).floor() as i64
}

/// How far `x` is from a tie (a fraction of one half). The table is only well defined if no cell is
/// close to one, or a different `exp` could round it the other way.
fn tie_distance(x: f64) -> f64 {
    ((x - x.floor()) - 0.5).abs()
}

/// The start of note `k` of `n` for a warp of `tenths` tenths, from the formula of SPEC-0005 section 4.
/// Returns the rounded tick and how close the unrounded value was to a tie (1.0 when exact).
fn formula(tenths: i32, span: i64, k: i64, n: i64) -> (u8, f64) {
    if tenths == 0 {
        // W(x) = x exactly: integer arithmetic, half up, so there is no float to disagree about.
        let num = 2 * span * (k - 1) + (n - 1);
        return (((num / (2 * (n - 1))) as u8), 1.0);
    }
    let a = 4.0 * tenths as f64 / 10.0;
    let x = (k - 1) as f64 / (n - 1) as f64;
    let w = ((a * x).exp() - 1.0) / (a.exp() - 1.0);
    let v = span as f64 * w;
    (half_up(v) as u8, tie_distance(v))
}

type Table = [[[[u8; 7]; 6]; 9]; 5];

/// The table the formula makes, and the closest any cell comes to a rounding tie.
fn generate() -> (Table, f64) {
    let mut table: Table = [[[[0; 7]; 6]; 9]; 5];
    let mut closest = 1.0f64;
    for (wi, warp) in Warp::ALL.iter().enumerate() {
        for level in 1..=9u8 {
            for n in 2..=7u8 {
                let span = strum_offset_ticks(level, n) as i64;
                for k in 1..=n {
                    let (tick, dist) = formula(warp.tenths() as i32, span, k as i64, n as i64);
                    table[wi][(level - 1) as usize][(n - 2) as usize][(k - 1) as usize] = tick;
                    closest = closest.min(dist);
                }
            }
        }
    }
    (table, closest)
}

