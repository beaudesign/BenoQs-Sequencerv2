#[test]
fn cv5_only_the_starts_move() {
    for style in STYLES.into_iter().skip(1) {
        for level in -9i8..=9 {
            for n in 1..=7usize {
                let manual = play(ChordStyle::Manual, level, n);
                let curved = play(style, level, n);
                let key = |p: &Played| {
                    let mut v: Vec<(u8, u8, u8, u8, u64)> = p.ons.iter().zip(&p.lengths).map(|(o, l)| (o.1, o.2, o.3, o.4, *l)).collect();
                    v.sort_unstable();
                    v
                };
                assert_eq!(key(&curved), key(&manual), "{style:?} level {level} n {n}: the same notes, velocities, channels, ports and lengths");
                // The order of the pitches in time: a negative level still reverses it.
                let order = |p: &Played| p.ons.iter().map(|o| o.1).collect::<Vec<u8>>();
                assert_eq!(order(&curved), order(&manual), "{style:?} level {level} n {n}: the same order of pitches");
                if level == 0 {
                    assert!(ticks(&curved).iter().all(|t| *t == 0), "{style:?} n {n}: level 0 is no roll");
                }
            }
        }
    }
    let up = play(ChordStyle::Curve(Warp::Bounce), 9, 4).ons.iter().map(|o| o.1).collect::<Vec<_>>();
    let down = play(ChordStyle::Curve(Warp::Bounce), -9, 4).ons.iter().map(|o| o.1).collect::<Vec<_>>();
    let mut reversed = up.clone();
    reversed.reverse();
    assert_eq!(down, reversed, "a negative strum plays the chord from the top");
}

