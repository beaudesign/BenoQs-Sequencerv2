/// A scene that draws a lot of random numbers: random directions, groove, chords larger than their
/// polyphony (random picks), and strums, on every track.
fn random_scene(seed: u64, style: ChordStyle) -> Engine {
    let mut rng = Rng::new(seed);
    let mut engine = Engine::new(seed);
    for (ti, track) in engine.grid.active_page_mut().tracks.iter_mut().enumerate() {
        track.midi_channel = 1 + ti as u8;
        track.direction_raw = [1, 4, 5][rng.next_below(3) as usize];
        track.groove = 2 * rng.next_below(9) as u8;
        for s in 0..STEP_COUNT {
            let step = &mut track.steps[s];
            step.active = rng.next_below(3) != 0;
            step.strum = rng.next_below(19) as i8 - 9;
            let size = 1 + rng.next_below(7) as usize;
            if size > 1 {
                step.chord.count = (size - 1) as u8;
                for k in 0..size - 1 {
                    step.chord.offsets[k] = 1 + rng.next_below(15) as i8;
                }
                step.chord.polyphony = 1 + rng.next_below(7) as u8;
            }
        }
    }
    for t in 0..TRACK_COUNT as u8 {
        assert!(engine.set_chord_style(t, style));
    }
    engine
}

fn run_seconds(engine: &mut Engine, seconds: f64) -> usize {
    let buffers = (seconds * SAMPLE_RATE as f64 / 512.0).ceil() as u32;
    let mut count = 0;
    for _ in 0..buffers {
        let mut buf = EventBuffer::new();
        engine.render(&RenderContext { sample_rate: SAMPLE_RATE, buffer_len: 512, bpm: 120.0, playing: true }, &mut buf);
        count += buf.as_slice().len();
    }
    count
}

#[test]
fn cv7_the_style_draws_no_random_number() {
    for seed in 0..24u64 {
        let mut manual = random_scene(seed, ChordStyle::Manual);
        let mut curved = random_scene(seed, ChordStyle::Curve(Warp::Bounce));
        let a = run_seconds(&mut manual, 12.0);
        run_seconds(&mut curved, 12.0);
        assert!(a > 100, "seed {seed}: a scene that plays nothing tests nothing");
        assert_eq!(manual.next_random_for_test(), curved.next_random_for_test(), "seed {seed}: Curve drew, or skipped, a random number");
    }
    // And the probe can tell: a different count of draws is a different next number.
    let mut a = random_scene(1, ChordStyle::Manual);
    let mut b = random_scene(1, ChordStyle::Manual);
    run_seconds(&mut a, 12.0);
    run_seconds(&mut b, 6.0);
    assert_ne!(a.next_random_for_test(), b.next_random_for_test());
}

/// The scenes of `invariants.rs`: every step of every track a strummed 6-note chord at 240 BPM (`dense` also runs
/// every track at 4x with groove and a phrase on every step, which is more than the queue can hold). Run for 20 seconds,
/// then stopped and drained. Returns the engine's counters and the notes still sounding at the end.
fn heavy(style: ChordStyle, strum: i8, dense: bool) -> (octocore::Diagnostics, usize) {
    let mut engine = Engine::new(5);
    for (ti, track) in engine.grid.active_page_mut().tracks.iter_mut().enumerate() {
        if dense {
            track.multiplier_num = 4;
            track.multiplier_den = 1;
            track.groove = 8;
        }
        for (si, step) in track.steps.iter_mut().enumerate() {
            step.active = true;
            step.strum = strum;
            step.chord.count = 6;
            step.chord.polyphony = 7;
            step.chord.offsets = [3, 4, 7, 10, 12, 16];
            if dense {
                step.phrase = Some(((ti * 3 + si) % 48 + 1) as u8);
            }
        }
    }
    for t in 0..TRACK_COUNT as u8 {
        engine.set_chord_style(t, style);
    }
    let mut net: BTreeMap<(u8, u8, u8), i64> = BTreeMap::new();
    let mut take = |engine: &mut Engine, playing: bool| {
        let mut buf = EventBuffer::new();
        engine.render(&RenderContext { sample_rate: SAMPLE_RATE, buffer_len: 64, bpm: 240.0, playing }, &mut buf);
        for e in buf.as_slice() {
            match *e {
                Event::NoteOn { port, ch, note, .. } => *net.entry((port, ch, note)).or_default() += 1,
                Event::NoteOff { port, ch, note, .. } => *net.entry((port, ch, note)).or_default() -= 1,
                _ => {}
            }
        }
    };
    for _ in 0..(20.0 * SAMPLE_RATE as f64 / 64.0) as u32 {
        take(&mut engine, true);
    }
    for _ in 0..64 {
        take(&mut engine, false);
    }
    let sounding = net.values().filter(|v| **v != 0).count();
    (engine.diagnostics(), sounding)
}

/// CV-8. The scene `invariants.rs` holds to "at most half the queue" is strum 5; in it every style keeps that bound. At the
/// strongest strum (9) the manual's own table already takes the queue to 490 of 1,024, and a style that puts the notes of
/// a roll late (Bounce, Accel) takes it to about 650: more than half, with nothing refused, deferred or late. That is what
/// the style does, and the bound it keeps is three quarters. In the overload scene every style refuses whole notes and
/// never sends one late.
#[test]
fn cv8_the_heavy_scenes_hold_in_every_style() {
    for style in STYLES {
        let (d, sounding) = heavy(style, 5, false);
        assert_eq!((d.queue_overflows, d.deferred_events, d.late_events), (0, 0, 0), "{style:?} strum 5: {d:?}");
        assert!(d.queue_high_water as usize * 2 <= octocore::QUEUE_CAP, "{style:?} strum 5: the queue reached {} of {}", d.queue_high_water, octocore::QUEUE_CAP);
        assert_eq!(sounding, 0, "{style:?} strum 5: notes left sounding");

        let (d, sounding) = heavy(style, 9, false);
        assert_eq!((d.queue_overflows, d.deferred_events, d.late_events), (0, 0, 0), "{style:?} strum 9: {d:?}");
        assert!(d.queue_high_water as usize * 4 <= octocore::QUEUE_CAP * 3, "{style:?} strum 9: the queue reached {} of {}", d.queue_high_water, octocore::QUEUE_CAP);
        assert_eq!(sounding, 0, "{style:?} strum 9: notes left sounding");

        let (d, sounding) = heavy(style, 9, true);
        assert!(d.queue_overflows > 0, "{style:?}: the overload scene should overflow the queue: {d:?}");
        assert_eq!(d.late_events, 0, "{style:?} overload: {d:?}");
        assert_eq!(sounding, 0, "{style:?} overload: a refused note left a half pair");
    }
}

